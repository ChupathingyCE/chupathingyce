#!/usr/bin/env python3
"""Compiles display.ray_tracing's compute
shaders (port/assets/shaders/modern_lighting/rt_trace.comp, the trace, and
rt_skin.comp, the render models' skinning) to SPIR-V with glslangValidator,
and writes them as C arrays that port/linux/src/posix_modern_lighting_rt.c
includes (port/linux/src/modern_lighting_rt_spv.h). Run it after changing a
shader:

    python3 tools/modern_lighting_spv.py

SPDX-FileCopyrightText: 2026 BirchWoodGod
SPDX-FileCopyrightText: 2026 The Chupathingy contributors
SPDX-License-Identifier: GPL-3.0-or-later
"""
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADERS = ROOT / "port" / "assets" / "shaders" / "modern_lighting"
# (the array's name, the shader)
SOURCES = [("modern_lighting_rt_spv", SHADERS / "rt_trace.comp"),
           ("modern_lighting_skin_spv", SHADERS / "rt_skin.comp")]
HEADER = ROOT / "port" / "linux" / "src" / "modern_lighting_rt_spv.h"


def main():
    lines = ["/* generated by tools/modern_lighting_spv.py from",
             "port/assets/shaders/modern_lighting/rt_trace.comp and rt_skin.comp: do not edit",
             "",
             "SPDX-FileCopyrightText: 2026 BirchWoodGod",
             "SPDX-FileCopyrightText: 2026 The Chupathingy contributors",
             "SPDX-License-Identifier: GPL-3.0-or-later */"]
    total = 0
    for name, source in SOURCES:
        with tempfile.TemporaryDirectory() as work:
            spv = Path(work) / "shader.spv"
            subprocess.run(["glslangValidator", "--target-env", "vulkan1.2", "-V", str(source), "-o", str(spv)],
                           check=True, stdout=subprocess.DEVNULL)
            data = spv.read_bytes()
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        total += len(words)
        lines += [f"static const unsigned int {name}[] =", "{"]
        for i in range(0, len(words), 8):
            lines.append("\t" + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
        lines += ["};", ""]
    HEADER.write_text("\n".join(lines))
    print(f"{HEADER.relative_to(ROOT)}: {total} words")


if __name__ == "__main__":
    sys.exit(main())
