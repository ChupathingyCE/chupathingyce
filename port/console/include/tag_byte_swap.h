/*
TAG_BYTE_SWAP.H

A map's tags in a big-endian console's byte order: each group's layout and
each tag block element's, as the game's own structures and code read them
(generated by tools/tag_swap_generate.py into
port/console/game/tag_byte_swap_tables.c), and the walker that applies them
(port/console/game/tag_byte_swap.c).
*/

#ifndef __TAG_BYTE_SWAP_H
#define __TAG_BYTE_SWAP_H

/* one step of a layout: op 2, 4 or 8 swaps argument fields of that many
bytes from offset; op 0 is a tag block at offset whose elements have
layout argument */
struct tag_swap_op
{
	unsigned long offset;
	unsigned long op;
	unsigned long argument;
};

struct tag_swap_layout
{
	unsigned long size;
	unsigned long first_op;
	unsigned long op_count;
};

struct tag_swap_group
{
	unsigned long group_tag;
	unsigned long layout;
};

extern const struct tag_swap_op tag_swap_ops[];
extern const struct tag_swap_layout tag_swap_layouts[];
extern const struct tag_swap_group tag_swap_groups[];
extern const int tag_swap_group_count;
extern const int tag_swap_layout_count;

/* every tag of a map, just loaded into the tag cache at base (whose Xbox
address is base_address, size bytes), its tag header and index already the
console's (cache_byte_swap.h) */
void tag_byte_swap_tags(void *base, unsigned long base_address, unsigned long size);

/* a structure BSP's tag (group 'sbsp'), just read at bsp (Xbox address
bsp_address), within the region [region_address, region_address +
region_size) its data was read into */
void tag_byte_swap_structure_bsp(void *bsp, unsigned long bsp_address, unsigned long region_address,
	unsigned long region_size);

#endif
