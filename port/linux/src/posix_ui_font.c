/* the fonts' data (tools/embed_assets.py --fonts, generated by the build:
32-bit words, which every build's assembly carries as they are) */
extern const unsigned int *const ui_font_files[POSIX_UI_FONT_COUNT];
#define font_data ((const unsigned char *const *)ui_font_files)

/* a font file, at most */
#define MAXIMUM_FILE_SIZE (32 * 1024 * 1024)

static struct
{
	int state; /* 0 not tried, 1 ready, -1 broken */
	stbtt_fontinfo info;
	/* a file's data drawn in place of the built-in face, or NULL */
	unsigned char *file;
} fonts[POSIX_UI_FONT_COUNT];

static stbtt_fontinfo *face(int font)
{
	if (font < 0 || font >= POSIX_UI_FONT_COUNT)
		return NULL;
	if (!fonts[font].state)
	{
		const unsigned char *data = fonts[font].file ? fonts[font].file : font_data[font];
		int offset = stbtt_GetFontOffsetForIndex(data, 0);

		fonts[font].state = offset >= 0 && stbtt_InitFont(&fonts[font].info, data, offset) ? 1 : -1;
	}
	return fonts[font].state > 0 ? &fonts[font].info : NULL;
}

int posix_ui_font_metrics(int font, float pixel_height, float *ascent, float *descent)
{
	stbtt_fontinfo *info = face(font);
	int ascent_units, descent_units, gap_units;
	float scale;

	if (!info)
		return 0;
	scale = stbtt_ScaleForPixelHeight(info, pixel_height);
	stbtt_GetFontVMetrics(info, &ascent_units, &descent_units, &gap_units);
	*ascent = (float)ascent_units * scale;
	*descent = (float)-descent_units * scale;
	return 1;
}

int posix_ui_font_has(int font, unsigned int codepoint)
{
	stbtt_fontinfo *info = face(font);

	return info && stbtt_FindGlyphIndex(info, (int)codepoint) != 0;
}

/* a question mark's room beyond a usual side bearing, in font units, on
the left (right 0) or the right: Cyborg Interface Gothic's sits in a full
em with nearly a quarter of it empty on each side, which read as a space
before it ("team ?"). Taken off between it and its neighbors, as kerning */
static int question_slack(stbtt_fontinfo *info, unsigned int codepoint, int right)
{
	int advance, bearing, x0, y0, x1, y1, usual, l_advance, side;

	if (codepoint != '?' || !stbtt_GetCodepointBox(info, (int)codepoint, &x0, &y0, &x1, &y1))
		return 0;
	stbtt_GetCodepointHMetrics(info, (int)codepoint, &advance, &bearing);
	/* (a usual side: the l's left bearing, else a twentieth of the advance) */
	if (stbtt_FindGlyphIndex(info, 'l'))
		stbtt_GetCodepointHMetrics(info, 'l', &l_advance, &usual);
	else
		usual = advance / 20;
	side = right ? advance - x1 : x0;
	return side > usual ? side - usual : 0;
}

float posix_ui_font_advance(int font, float pixel_height, unsigned int codepoint, unsigned int previous)
{
	stbtt_fontinfo *info = face(font);
	int advance, bearing;
	float scale, width;

	if (!info)
		return 0.0f;
	scale = stbtt_ScaleForPixelHeight(info, pixel_height);
	stbtt_GetCodepointHMetrics(info, (int)codepoint, &advance, &bearing);
	width = (float)advance * scale;
	if (previous)
	{
		width += (float)stbtt_GetCodepointKernAdvance(info, (int)previous, (int)codepoint) * scale;
		/* (a question mark drawn close to the word before it and the one after) */
		if (previous != ' ')
			width -= (float)question_slack(info, codepoint, 0) * scale;
		if (codepoint != ' ')
			width -= (float)question_slack(info, previous, 1) * scale;
		else
			width -= (float)question_slack(info, previous, 1) * scale * 0.5f;
	}
	return width;
}

unsigned char *posix_ui_font_glyph(int font, float pixel_height, unsigned int codepoint, int *width, int *height,
	int *x_offset, int *y_offset)
{
	stbtt_fontinfo *info = face(font);

	*width = *height = *x_offset = *y_offset = 0;
	if (!info)
		return NULL;
	return stbtt_GetCodepointBitmap(info, 0, stbtt_ScaleForPixelHeight(info, pixel_height), (int)codepoint,
		width, height, x_offset, y_offset);
}

void posix_ui_font_free(unsigned char *bitmap)
{
	stbtt_FreeBitmap(bitmap, NULL);
}

int posix_ui_font_use_file(int font, const char *path)
{
	FILE *file;
	long size = -1;
	unsigned char *data = NULL;
	stbtt_fontinfo info;
	int offset;

	if (font < 0 || font >= POSIX_UI_FONT_COUNT)
		return 0;
	free(fonts[font].file);
	fonts[font].file = NULL;
	fonts[font].state = 0;
	if (!path || !*path || !(file = fopen(path, "rb")))
		return 0;
	if (fseek(file, 0, SEEK_END) == 0)
		size = ftell(file);
	if (size <= 0 || size > MAXIMUM_FILE_SIZE || fseek(file, 0, SEEK_SET) != 0 || !(data = malloc((size_t)size)) ||
		fread(data, 1, (size_t)size, file) != (size_t)size)
	{
		free(data);
		fclose(file);
		return 0;
	}
	fclose(file);
	offset = stbtt_GetFontOffsetForIndex(data, 0);
	if (offset < 0 || !stbtt_InitFont(&info, data, offset))
	{
		free(data);
		return 0;
	}
	fonts[font].file = data;
	return 1;
}

unsigned char *posix_ui_image_decode(const unsigned char *data, int size, int *width, int *height)
{
	int channels = 0;
	unsigned char *pixels;

	*width = *height = 0;
	if (!data || size <= 0 || !stbi_info_from_memory(data, size, width, height, &channels) ||
		*width <= 0 || *height <= 0 || *width > POSIX_UI_IMAGE_LARGEST || *height > POSIX_UI_IMAGE_LARGEST)
	{
		*width = *height = 0;
		return NULL;
	}
	pixels = stbi_load_from_memory(data, size, width, height, &channels, 4);
	if (!pixels)
		*width = *height = 0;
	return pixels;
}

void posix_ui_image_free(unsigned char *pixels)
{
	stbi_image_free(pixels);
}

