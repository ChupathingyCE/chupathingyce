/* Metal translation of port/linux/src/xgpu_post.c's FXAA. Same thresholds,
   twelve bounded search steps, view-clamped samples, and RGB-only output.
   Kept as C text so an offscreen test can compile the exact production MSL. */
#ifndef HALO_METAL_FXAA_SOURCE_H
#define HALO_METAL_FXAA_SOURCE_H
static const char metal_fxaa_source[] =
"#include <metal_stdlib>\n"
"using namespace metal;\n"
"vertex float4 fxaa_vertex(uint id [[vertex_id]]) {\n"
"    return float4(id == 1 ? 3.0 : -1.0, id == 2 ? 3.0 : -1.0, 0, 1);\n"
"}\n"
"fragment float4 fxaa_fragment(float4 pixel [[position]], texture2d<float> color [[texture(0)]],\n"
"    sampler linear [[sampler(0)]], constant float4 &metrics [[buffer(0)]],\n"
"    constant float4 &bounds [[buffer(1)]]) {\n"
"#define color_at(p) color.sample(linear, clamp((p), bounds.xy, bounds.zw), level(0.0)).rgb\n"
"#define luma_at(p) dot(color_at(p), float3(0.299, 0.587, 0.114))\n"
"    const float steps[12] = {1,1,1,1,1,1.5,2,2,2,2,4,8};\n"
"    float2 position = pixel.xy * metrics.xy;\n"
"    float luma = luma_at(position);\n"
"    float up = luma_at(position + float2(0, -metrics.y));\n"
"    float down = luma_at(position + float2(0, metrics.y));\n"
"    float left = luma_at(position + float2(-metrics.x, 0));\n"
"    float right = luma_at(position + float2(metrics.x, 0));\n"
"    float highest = max(luma, max(max(up, down), max(left, right)));\n"
"    float range = highest - min(luma, min(min(up, down), min(left, right)));\n"
"    if (range < max(0.0312, highest * 0.125)) discard_fragment();\n"
"    float up_left = luma_at(position + float2(-metrics.x, -metrics.y));\n"
"    float up_right = luma_at(position + float2(metrics.x, -metrics.y));\n"
"    float down_left = luma_at(position + float2(-metrics.x, metrics.y));\n"
"    float down_right = luma_at(position + float2(metrics.x, metrics.y));\n"
"    float average = (2.0 * (up + down + left + right) + up_left + up_right + down_left + down_right) / 12.0;\n"
"    float subpixel = smoothstep(0.0, 1.0, clamp(abs(average - luma) / range, 0.0, 1.0));\n"
"    subpixel = subpixel * subpixel * 0.75;\n"
"    bool horizontal = abs(up_left + down_left - 2.0 * left) + 2.0 * abs(up + down - 2.0 * luma) +\n"
"        abs(up_right + down_right - 2.0 * right) >= abs(up_left + up_right - 2.0 * up) +\n"
"        2.0 * abs(left + right - 2.0 * luma) + abs(down_left + down_right - 2.0 * down);\n"
"    float before = horizontal ? up : left;\n"
"    float after = horizontal ? down : right;\n"
"    bool before_steeper = abs(before - luma) >= abs(after - luma);\n"
"    float gradient = 0.25 * max(abs(before - luma), abs(after - luma));\n"
"    float edge_luma = 0.5 * ((before_steeper ? before : after) + luma);\n"
"    float2 across = (horizontal ? float2(0, metrics.y) : float2(metrics.x, 0)) * (before_steeper ? -1.0 : 1.0);\n"
"    float2 along = horizontal ? float2(metrics.x, 0) : float2(0, metrics.y);\n"
"    float2 end_before = position + 0.5 * across - along;\n"
"    float2 end_after = position + 0.5 * across + along;\n"
"    float luma_before = luma_at(end_before) - edge_luma;\n"
"    float luma_after = luma_at(end_after) - edge_luma;\n"
"    bool reached_before = abs(luma_before) >= gradient;\n"
"    bool reached_after = abs(luma_after) >= gradient;\n"
"    for (int index = 1; index < 12 && !(reached_before && reached_after); index++) {\n"
"        if (!reached_before) {\n"
"            end_before -= along * steps[index];\n"
"            luma_before = luma_at(end_before) - edge_luma;\n"
"            reached_before = abs(luma_before) >= gradient;\n"
"        }\n"
"        if (!reached_after) {\n"
"            end_after += along * steps[index];\n"
"            luma_after = luma_at(end_after) - edge_luma;\n"
"            reached_after = abs(luma_after) >= gradient;\n"
"        }\n"
"    }\n"
"    float distance_before = horizontal ? position.x - end_before.x : position.y - end_before.y;\n"
"    float distance_after = horizontal ? end_after.x - position.x : end_after.y - position.y;\n"
"    float pixel_offset = 0.5 - min(distance_before, distance_after) / (distance_before + distance_after);\n"
"    bool varies = ((distance_before < distance_after ? luma_before : luma_after) < 0.0) != (luma < edge_luma);\n"
"    return float4(color_at(position + max(varies ? pixel_offset : 0.0, subpixel) * across), 1);\n"
"}\n";
#endif
